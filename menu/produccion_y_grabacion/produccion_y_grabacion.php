           <h2 class="centrado">Efectos prácticos a gran escala: El trabajo de New Deal Studios</h2>
             <p>Además de construir los interiores de las naves para que los actores pudieran tocarlas, la producción necesitaba tomas exteriores ultra realistas. En lugar de hacer las naves 100% por computadora, el equipo contrató a New Deal Studios para crear maquetas a gran escala (a veces llamadas "maxiaturas" por su inmenso tamaño). Construyeron versiones físicas detalladas de la Endurance, la Ranger y la Lander, algunas midiendo hasta 15 metros de largo. Como las cámaras IMAX eran tan enormes, tuvieron que montar sistemas de grúas robóticas especiales para que la cámara "volara" alrededor de estas maquetas, logrando texturas y rebotes de luz que la computadora difícilmente puede igualar.</p>
         </div>
     
           <div class="caja-datos-produccion" >
           <h2 class="centrado">El debate en la sala de mezcla de sonido</h2>
             <p>El proceso de postproducción de sonido fue uno de los más desafiantes y polémicos de la década. En las salas de mezcla, Christopher Nolan tomó la arriesgada decisión artística de subir el volumen de los motores de la nave y la música por encima de los diálogos en momentos clave. Su objetivo en el estudio no era que el espectador escuchara cada palabra a la perfección, sino que sintiera físicamente en la sala de cine la vibración, la claustrofobia y el terror de estar dentro de una nave espacial siendo arrastrada por la gravedad de un agujero negro.</p>
