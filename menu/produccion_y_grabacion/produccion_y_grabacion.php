    <h2 class="centrado">El formato de filmación: IMAX y 70 mm</h2>
     <p>A nivel técnico, el proceso de filmación fue un desafío extremo. Christopher Nolan es un firme defensor del cine analógico, por lo que Interstellar se filmó combinando el formato anamórfico de 35 mm con el formato IMAX de 70 mm. El uso de las pesadas y ruidosas cámaras IMAX obligó al equipo de producción a rediseñar cómo se grababan los diálogos en el set. El resultado de este esfuerzo técnico fue una resolución de imagen sin precedentes, que permitió que la audiencia se sintiera verdaderamente inmersa en la inmensidad del espacio exterior cuando la película llegó a las salas de cine preparadas para este formato.</p>
    </div>
