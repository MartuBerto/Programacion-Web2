       <h2 class="centrado">La logística extrema en los glaciares</h2>
       <p>Convertir a Islandia en un set de filmación de Hollywood requirió un nivel de planificación propio de una expedición militar. Para grabar en la locación de Mafábot (el planeta acuático de Miller), el equipo de producción tuvo que construir más de 15 kilómetros de caminos improvisados para que los camiones de equipo pesado pudieran llegar al lugar. Filmar allí significó operar cámaras eléctricas valuadas en cientos de miles de dólares a centímetros del agua salada, mientras los actores debían moverse usando trajes espaciales reales que pesaban más de 15 kilos al empaparse.</p>
      </div>
    </article>

