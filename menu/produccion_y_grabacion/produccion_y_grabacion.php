      <h2 class="centrado">Los sets de grabación y foros principales</h2>
       <p>Aunque la película es famosa por sus impresionantes locaciones reales en Islandia y Canadá, todas las escenas de interiores, las naves espaciales y las complejas secuencias de gravedad cero requirieron instalaciones de primer nivel. El rodaje de estos interiores se llevó a cabo en los históricos foros de sonido de Sony Pictures Studios en Culver City, California, y en las gigantescas instalaciones de Warner Bros. Studios en Burbank. En lugar de usar pantallas verdes, el equipo de diseño de producción construyó los interiores de las naves Ranger y Endurance a escala real dentro de estos estudios, permitiendo a los actores interactuar físicamente con los paneles y los espacios reducidos.</p>
       <p>Para llevar este realismo al extremo, rodearon estas naves físicas con pantallas gigantes que proyectaban el espacio exterior y el imponente agujero negro "Gargantúa" en tiempo real. Gracias a esta técnica revolucionaria, cuando los actores miraban por las ventanas, realmente estaban viendo el disco de luz del agujero negro, logrando que esos destellos se reflejaran de forma auténtica en sus cascos y consolas.</p> 
       <p>Esta ambición técnica alcanzó su punto máximo con la construcción del Teseracto, la estructura de la quinta dimensión. Lejos de ser un efecto digital, se construyó un set físico masivo de tres pisos de altura que representaba una red geométrica infinita de estanterías y libros. Matthew McConaughey tuvo que filmar estas secuencias suspendido por cables de alta resistencia dentro de este laberinto real, permitiendo que su desesperación al intentar "tocar" el tiempo fuera tangible y físicamente real, convirtiéndose en uno de los sets más complejos jamás construidos en la historia de los estudios de Hollywood. </p>
