      <h2 class="centrado">La grabación de una banda sonora histórica</h2>
       <p>El concepto de "estudio de grabación" en Interstellar no solo abarca la imagen, sino también su inconfundible sonido. El compositor Hans Zimmer y Christopher Nolan trabajaron de una forma muy poco convencional: Nolan le pidió a Zimmer que compusiera el tema principal sin ver un solo fotograma de la película, basándose únicamente en una breve historia sobre un padre y su hijo. Una vez que la música fue compuesta, las sesiones de grabación más importantes no se hicieron en un estudio tradicional de Hollywood. Para lograr el sonido masivo e imponente que requería el espacio, el equipo se trasladó a Londres para grabar en la histórica Temple Church, utilizando su gigantesco órgano de tubos de 1926, combinado con orquestas grabadas en los prestigiosos Lyndhurst Hall (Air Studios).</p>
    </div>

