          <p>Las apocalípticas tormentas de polvo que ahogan a la Tierra tampoco son CGI (efectos generados por computadora). El equipo de efectos especiales utilizó un material llamado C-90, que es básicamente cartón triturado hasta convertirse en un polvo finísimo y seguro para los pulmones de los actores. Utilizaron ventiladores gigantes para soplar este polvo sobre las casas, las camionetas y el elenco, logrando un efecto físico completamente asfixiante y real.</p>
        </div>

