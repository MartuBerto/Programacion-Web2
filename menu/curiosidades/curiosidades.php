          <h2 class="centrado">El tictac en el Planeta Miller:</h2>
          <p>Este es uno de los detalles más alucinantes de la película. Durante la escena en el planeta oceánico de Miller (donde el tiempo pasa muchísimo más lento debido a la gravedad del agujero negro), la banda sonora de Hans Zimmer tiene un sonido de "tictac" rítmico de fondo. Cada uno de esos "tics" ocurre exactamente cada 1.25 segundos. En la relatividad de ese planeta, cada tictac representa un día entero que acaba de transcurrir en la Tierra.</p>
