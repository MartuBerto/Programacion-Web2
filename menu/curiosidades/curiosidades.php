          <h2>TARS y CASE no eran robots digitales:</h2>
          <p>Los peculiares robots tácticos de la película, TARS y CASE, parecen puramente hechos por computadora, pero en realidad eran marionetas gigantes. Se construyeron versiones físicas de acero y aluminio que pesaban alrededor de 90 kilos. El actor Bill Irwin se escondía detrás del robot TARS, operando sus movimientos mecánicamente en el set y haciendo la voz en vivo para que los demás actores pudieran interactuar con él de manera natural. Solo se usó CGI para borrar al actor en la postproducción y para los movimientos más complejos.</p>
        </div>

        <div class="caja-curiosidades">
          <h2 class="centrado">El secreto de la banda sonora:</h2>
          <p>Cuando Christopher Nolan contrató al legendario compositor Hans Zimmer, le ocultó de qué trataba la película. No le dijo que era una superproducción espacial, ni que habría naves, ni el título. Solo le entregó una sola página escrita a máquina que narraba la historia de un padre que debía dejar atrás a su hijo para hacer un trabajo importante, y le pidió que compusiera la música basándose solo en ese sentimiento de separación. Esa pieza íntima se convirtió en el tema principal de toda la película.</p>
        </div>

        <div class="caja-curiosidades">
          <h2 class="centrado">Hipotermia espacial en Islandia:</h2>
          <p>Durante la grabación en el planeta acuático de Miller (filmado en la laguna glaciar de Mafábot, en Islandia), Anne Hathaway (la Dra. Brand) pasó un muy mal momento. Su traje espacial tenía un cierre mal sellado, lo que provocó que se llenara lentamente de agua helada del glaciar mientras filmaban las escenas donde caminan por el agua. La actriz aguantó la escena casi hasta el final antes de avisar que estaba empezando a sufrir los primeros síntomas de hipotermia.</p>
